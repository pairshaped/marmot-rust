#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TemporalParseError {
    value: String,
    expected: &'static str,
}

impl fmt::Display for TemporalParseError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "invalid temporal value {:?}; expected {}", self.value, self.expected)
    }
}

impl std::error::Error for TemporalParseError {}

#[derive(Debug)]
struct TemporalFieldError {
    field: &'static str,
    source: rusqlite::Error,
}

impl fmt::Display for TemporalFieldError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if let rusqlite::Error::FromSqlConversionFailure(_, _, source) = &self.source
            && let Some(source) = source.downcast_ref::<TemporalParseError>()
        {
            return write!(
                f,
                "invalid temporal value for {}: {:?}; expected {}",
                self.field, source.value, source.expected
            );
        }
        write!(
            f,
            "could not decode temporal field {:?}: {}",
            self.field, self.source
        )
    }
}

impl std::error::Error for TemporalFieldError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        Some(&self.source)
    }
}

pub(crate) fn with_field<T>(
    result: rusqlite::Result<T>,
    field: &'static str,
    index: usize,
) -> rusqlite::Result<T> {
    result.map_err(|source| {
        let data_type = match &source {
            rusqlite::Error::FromSqlConversionFailure(_, data_type, _) => *data_type,
            _ => return source,
        };
        rusqlite::Error::FromSqlConversionFailure(
            index,
            data_type,
            Box::new(TemporalFieldError { field, source }),
        )
    })
}

fn validate_datetime(value: &str) -> Result<(), TemporalParseError> {
    if value.len() != 19 || value.as_bytes().get(10) != Some(&b' ') {
        return Err(temporal_error(value, "YYYY-MM-DD HH:MM:SS"));
    }
    validate_date(&value[..10]).map_err(|_| temporal_error(value, "YYYY-MM-DD HH:MM:SS"))?;
    let bytes = value.as_bytes();
    if bytes.get(13) != Some(&b':') || bytes.get(16) != Some(&b':') {
        return Err(temporal_error(value, "YYYY-MM-DD HH:MM:SS"));
    }
    let hour = parse_two_digits(value, 11, "YYYY-MM-DD HH:MM:SS")?;
    let minute = parse_two_digits(value, 14, "YYYY-MM-DD HH:MM:SS")?;
    let second = parse_two_digits(value, 17, "YYYY-MM-DD HH:MM:SS")?;
    if hour > 23 || minute > 59 || second > 59 {
        return Err(temporal_error(value, "YYYY-MM-DD HH:MM:SS"));
    }
    Ok(())
}

fn validate_date(value: &str) -> Result<(), TemporalParseError> {
    if value.len() != 10 {
        return Err(temporal_error(value, "YYYY-MM-DD"));
    }
    let bytes = value.as_bytes();
    if bytes.get(4) != Some(&b'-') || bytes.get(7) != Some(&b'-') {
        return Err(temporal_error(value, "YYYY-MM-DD"));
    }
    let year = parse_four_digits(value, 0, "YYYY-MM-DD")?;
    let month = parse_two_digits(value, 5, "YYYY-MM-DD")?;
    let day = parse_two_digits(value, 8, "YYYY-MM-DD")?;
    if month == 0 || month > 12 || day == 0 || day > days_in_month(year, month) {
        return Err(temporal_error(value, "YYYY-MM-DD"));
    }
    Ok(())
}

fn parse_four_digits(value: &str, start: usize, expected: &'static str) -> Result<u32, TemporalParseError> {
    let slice = value.get(start..start + 4).ok_or_else(|| temporal_error(value, expected))?;
    if !slice.bytes().all(|byte| byte.is_ascii_digit()) {
        return Err(temporal_error(value, expected));
    }
    Ok(slice.parse().expect("four ASCII digits should parse as u32"))
}

fn parse_two_digits(value: &str, start: usize, expected: &'static str) -> Result<u32, TemporalParseError> {
    let slice = value.get(start..start + 2).ok_or_else(|| temporal_error(value, expected))?;
    if !slice.bytes().all(|byte| byte.is_ascii_digit()) {
        return Err(temporal_error(value, expected));
    }
    Ok(slice.parse().expect("two ASCII digits should parse as u32"))
}

fn days_in_month(year: u32, month: u32) -> u32 {
    match month {
        1 | 3 | 5 | 7 | 8 | 10 | 12 => 31,
        4 | 6 | 9 | 11 => 30,
        2 if is_leap_year(year) => 29,
        2 => 28,
        _ => 0,
    }
}

fn is_leap_year(year: u32) -> bool {
    (year.is_multiple_of(4) && !year.is_multiple_of(100)) || year.is_multiple_of(400)
}

fn temporal_error(value: &str, expected: &'static str) -> TemporalParseError {
    TemporalParseError {
        value: value.to_string(),
        expected,
    }
}
