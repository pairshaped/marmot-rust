use std::collections::{BTreeMap, BTreeSet};
use std::fs;

use heck::ToPascalCase;

use crate::config::Config;
use crate::error::{Error, Result};
use crate::model::{Column, Project, Query, ReturnType};

pub fn emit(config: &Config, project: &Project) -> Result<()> {
    let mut by_module: BTreeMap<&str, Vec<&Query>> = BTreeMap::new();
    for query in &project.queries {
        by_module.entry(&query.module_name).or_default().push(query);
    }

    fs::create_dir_all(&config.output).map_err(|source| Error::CreateDir {
        path: config.output.clone(),
        source,
    })?;

    let modules = by_module.keys().copied().collect::<Vec<_>>();

    for (module, queries) in by_module {
        let path = config.output.join(format!("{module}.rs"));
        let content = render_module(queries)?;
        if config.check {
            let current = fs::read_to_string(&path).map_err(|source| Error::ReadFile {
                path: path.clone(),
                source,
            })?;
            if current != content {
                return Err(Error::StaleGeneratedFile { path });
            }
            continue;
        }
        fs::write(&path, content).map_err(|source| Error::WriteFile {
            path: path.clone(),
            source,
        })?;
    }

    emit_mod_rs(config, modules)
}

fn emit_mod_rs(config: &Config, modules: Vec<&str>) -> Result<()> {
    let path = config.output.join("mod.rs");
    let content = modules
        .into_iter()
        .map(|module| format!("pub mod {module};\n"))
        .collect::<String>();

    if config.check {
        let current = fs::read_to_string(&path).map_err(|source| Error::ReadFile {
            path: path.clone(),
            source,
        })?;
        if current != content {
            return Err(Error::StaleGeneratedFile { path });
        }
        return Ok(());
    }

    fs::write(&path, content).map_err(|source| Error::WriteFile {
        path: path.clone(),
        source,
    })
}

fn render_module(queries: Vec<&Query>) -> Result<String> {
    validate_shared_row_types(&queries)?;
    let import_macros = render_import_macros(&queries);
    let mut output = format!(
        "// This file is generated by Marmot. Do not edit by hand.\n\
         #![allow(dead_code)]\n\
         use rusqlite::{{{import_macros}Connection, Result}};\n\n",
    );
    let mut emitted_row_types = BTreeSet::new();

    for query in queries {
        let include_row_struct = match &query.return_type {
            ReturnType::Rows {
                row_type: Some(row_type),
            } if query.columns.len() > 1 => emitted_row_types.insert(row_type.clone()),
            _ => true,
        };
        output.push_str(&render_query(query, include_row_struct));
        output.push('\n');
    }

    Ok(output)
}

fn render_import_macros(queries: &[&Query]) -> String {
    let uses_named = queries.iter().any(|query| {
        query
            .parameters
            .iter()
            .any(|param| !param.sql_names.is_empty())
    });
    let uses_positional = queries.iter().any(|query| {
        !query.parameters.is_empty()
            && query
                .parameters
                .iter()
                .all(|param| param.sql_names.is_empty())
    });
    let mut imports = Vec::new();
    if uses_named {
        imports.push("named_params");
    }
    if uses_positional {
        imports.push("params");
    }

    if imports.is_empty() {
        String::new()
    } else {
        format!("{}, ", imports.join(", "))
    }
}

fn validate_shared_row_types(queries: &[&Query]) -> Result<()> {
    let mut shared_rows: BTreeMap<&str, &[Column]> = BTreeMap::new();
    for query in queries {
        let ReturnType::Rows {
            row_type: Some(row_type),
        } = &query.return_type
        else {
            continue;
        };

        if let Some(existing_columns) = shared_rows.get(row_type.as_str()) {
            if *existing_columns != query.columns.as_slice() {
                return Err(Error::SharedRowTypeMismatch {
                    row_type: row_type.clone(),
                });
            }
        } else {
            shared_rows.insert(row_type, query.columns.as_slice());
        }
    }

    Ok(())
}

fn render_query(query: &Query, include_row_struct: bool) -> String {
    let const_name = format!("{}_SQL", query.name.to_uppercase());
    let sql = raw_string(&query.sql);

    let mut output = format!("const {const_name}: &str = {sql};\n\n");
    match &query.return_type {
        ReturnType::Execute => output.push_str(&render_execute(query, &const_name)),
        ReturnType::Rows { .. } if query.columns.len() == 1 => {
            output.push_str(&render_scalar_select(query, &const_name))
        }
        ReturnType::Rows { .. } => {
            output.push_str(&render_select(query, &const_name, include_row_struct))
        }
    }
    output
}

fn render_select(query: &Query, const_name: &str, include_row_struct: bool) -> String {
    let ReturnType::Rows { row_type } = &query.return_type else {
        unreachable!("render_select only accepts row queries")
    };
    let row_type = row_type
        .clone()
        .unwrap_or_else(|| format!("{}Row", query.name.to_pascal_case()));
    let fields = query
        .columns
        .iter()
        .map(|column| format!("    pub {}: {},\n", column.field_name, column.rust_type()))
        .collect::<String>();
    let params = render_params(query);
    let named_params = render_named_params(query);
    let row_fields = query
        .columns
        .iter()
        .enumerate()
        .map(|(index, column)| format!("            {}: row.get({index})?,\n", column.field_name))
        .collect::<String>();

    let struct_definition = if include_row_struct {
        format!(
            "#[derive(Debug, Clone, PartialEq)]\n\
             pub struct {row_type} {{\n{fields}}}\n\n"
        )
    } else {
        String::new()
    };

    format!(
        "{struct_definition}\
         pub fn {name}(conn: &Connection{params}) -> Result<Vec<{row_type}>> {{\n\
             let mut stmt = conn.prepare_cached({const_name})?;\n\
             let rows = stmt.query_map({named_params}, |row| {{\n\
                 Ok({row_type} {{\n{row_fields}        }})\n\
             }})?;\n\
             rows.collect()\n\
         }}\n",
        name = query.name
    )
}

fn render_scalar_select(query: &Query, const_name: &str) -> String {
    let rust_type = query.columns[0].rust_type();
    let params = render_params(query);
    let named_params = render_named_params(query);
    format!(
        "pub fn {name}(conn: &Connection{params}) -> Result<Vec<{rust_type}>> {{\n\
             let mut stmt = conn.prepare_cached({const_name})?;\n\
             let rows = stmt.query_map({named_params}, |row| row.get(0))?;\n\
             rows.collect()\n\
         }}\n\n\
         pub fn {name}_one(conn: &Connection{params}) -> Result<{rust_type}> {{\n\
             let mut stmt = conn.prepare_cached({const_name})?;\n\
             stmt.query_row({named_params}, |row| row.get(0))\n\
         }}\n",
        name = query.name
    )
}

fn render_execute(query: &Query, const_name: &str) -> String {
    let params = render_params(query);
    let named_params = render_named_params(query);
    format!(
        "pub fn {name}(conn: &Connection{params}) -> Result<usize> {{\n\
             conn.execute({const_name}, {named_params})\n\
         }}\n",
        name = query.name
    )
}

fn render_params(query: &Query) -> String {
    query
        .parameters
        .iter()
        .map(|param| format!(", {}: {}", param.name, param.rust_argument_type()))
        .collect()
}

fn render_named_params(query: &Query) -> String {
    if query.parameters.is_empty() {
        return "[]".to_string();
    }

    if query
        .parameters
        .iter()
        .all(|param| param.sql_names.is_empty())
    {
        let names = query
            .parameters
            .iter()
            .map(param_binding_expr)
            .collect::<Vec<_>>()
            .join(", ");
        return format!("params![{names}]");
    }

    let pairs = query
        .parameters
        .iter()
        .flat_map(|param| {
            param
                .sql_names
                .iter()
                .map(|sql_name| format!("{sql_name:?}: {}", param_binding_expr(param)))
        })
        .collect::<Vec<_>>()
        .join(", ");
    format!("named_params! {{ {pairs} }}")
}

fn param_binding_expr(param: &crate::model::Parameter) -> String {
    if !param.nullable
        && matches!(
            param.column_type,
            crate::model::ValueType::String | crate::model::ValueType::Bytes
        )
    {
        format!("{}.as_ref()", param.name)
    } else {
        param.name.clone()
    }
}

fn raw_string(value: &str) -> String {
    for hashes in 0..8 {
        let marker = "#".repeat(hashes);
        let terminator = format!("\"{marker}");
        if !value.contains(&terminator) {
            return format!("r{marker}\"{value}\"{marker}");
        }
    }
    format!("{value:?}")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{Column, Parameter, Query, ValueType};
    use std::path::PathBuf;

    #[test]
    fn render_named_params_preserves_sql_placeholder_prefixes() {
        let query = Query {
            source_path: PathBuf::from("src/posts/sql/search.sql"),
            module_name: "posts_sql".to_string(),
            name: "search".to_string(),
            return_type: ReturnType::Execute,
            sql: "update posts set viewed = 1 where user_id = @user_id and created_at >= :since and title like $pattern or owner_id = :user_id".to_string(),
            parameters: vec![
                Parameter {
                    name: "user_id".to_string(),
                    sql_names: vec!["@user_id".to_string(), ":user_id".to_string()],
                    column_type: ValueType::I64,
                    nullable: false,
                },
                Parameter {
                    name: "since".to_string(),
                    sql_names: vec![":since".to_string()],
                    column_type: ValueType::I64,
                    nullable: false,
                },
                Parameter {
                    name: "pattern".to_string(),
                    sql_names: vec!["$pattern".to_string()],
                    column_type: ValueType::String,
                    nullable: false,
                },
            ],
            columns: vec![],
        };

        let output = render_query(&query, true);

        assert!(output.contains("\"@user_id\": user_id"));
        assert!(output.contains("\":user_id\": user_id"));
        assert!(output.contains("\":since\": since"));
        assert!(output.contains("\"$pattern\": pattern.as_ref()"));
    }

    #[test]
    fn render_positional_params_uses_params_macro() {
        let query = Query {
            source_path: PathBuf::from("src/users/sql/find.sql"),
            module_name: "users_sql".to_string(),
            name: "find".to_string(),
            return_type: ReturnType::Execute,
            sql: "update users set name = ? where id = ?".to_string(),
            parameters: vec![
                Parameter {
                    name: "param".to_string(),
                    sql_names: vec![],
                    column_type: ValueType::String,
                    nullable: false,
                },
                Parameter {
                    name: "param_2".to_string(),
                    sql_names: vec![],
                    column_type: ValueType::I64,
                    nullable: false,
                },
            ],
            columns: vec![],
        };

        let output = render_query(&query, true);

        assert!(output.contains("params![param.as_ref(), param_2]"));
    }

    #[test]
    fn render_query_uses_inferred_parameter_types() {
        let query = Query {
            source_path: PathBuf::from("src/users/sql/find.sql"),
            module_name: "users_sql".to_string(),
            name: "find".to_string(),
            return_type: ReturnType::Execute,
            sql: "update users set bio = @bio where id = @id".to_string(),
            parameters: vec![
                Parameter {
                    name: "bio".to_string(),
                    sql_names: vec!["@bio".to_string()],
                    column_type: ValueType::String,
                    nullable: true,
                },
                Parameter {
                    name: "id".to_string(),
                    sql_names: vec!["@id".to_string()],
                    column_type: ValueType::I64,
                    nullable: false,
                },
            ],
            columns: vec![],
        };

        let output = render_query(&query, true);

        assert!(output.contains("bio: Option<&str>"));
        assert!(output.contains("id: i64"));
        assert!(!output.contains("impl rusqlite::ToSql"));
    }

    #[test]
    fn render_module_emits_shared_row_type_once() {
        let columns = vec![
            Column {
                name: "id".to_string(),
                field_name: "id".to_string(),
                column_type: ValueType::I64,
                nullable: false,
            },
            Column {
                name: "name".to_string(),
                field_name: "name".to_string(),
                column_type: ValueType::String,
                nullable: false,
            },
        ];
        let query_1 = Query {
            source_path: PathBuf::from("src/orgs/sql/find_org.sql"),
            module_name: "orgs_sql".to_string(),
            name: "find_org".to_string(),
            return_type: ReturnType::Rows {
                row_type: Some("OrgRow".to_string()),
            },
            sql: "-- returns: OrgRow\nselect id, name from orgs where id = @id".to_string(),
            parameters: vec![Parameter {
                name: "id".to_string(),
                sql_names: vec!["@id".to_string()],
                column_type: ValueType::I64,
                nullable: false,
            }],
            columns: columns.clone(),
        };
        let query_2 = Query {
            source_path: PathBuf::from("src/orgs/sql/list_orgs.sql"),
            module_name: "orgs_sql".to_string(),
            name: "list_orgs".to_string(),
            return_type: ReturnType::Rows {
                row_type: Some("OrgRow".to_string()),
            },
            sql: "-- returns: OrgRow\nselect id, name from orgs".to_string(),
            parameters: vec![],
            columns,
        };

        let output = render_module(vec![&query_1, &query_2]).unwrap();

        assert_eq!(output.matches("pub struct OrgRow").count(), 1);
        assert!(output.contains("pub fn find_org(conn: &Connection"));
        assert!(output.contains("pub fn list_orgs(conn: &Connection"));
        assert_eq!(output.matches("Result<Vec<OrgRow>>").count(), 2);
    }

    #[test]
    fn render_module_rejects_shared_row_type_mismatches() {
        let query_1 = Query {
            source_path: PathBuf::from("src/orgs/sql/find_org.sql"),
            module_name: "orgs_sql".to_string(),
            name: "find_org".to_string(),
            return_type: ReturnType::Rows {
                row_type: Some("OrgRow".to_string()),
            },
            sql: "-- returns: OrgRow\nselect id from orgs".to_string(),
            parameters: vec![],
            columns: vec![Column {
                name: "id".to_string(),
                field_name: "id".to_string(),
                column_type: ValueType::I64,
                nullable: false,
            }],
        };
        let query_2 = Query {
            source_path: PathBuf::from("src/orgs/sql/list_orgs.sql"),
            module_name: "orgs_sql".to_string(),
            name: "list_orgs".to_string(),
            return_type: ReturnType::Rows {
                row_type: Some("OrgRow".to_string()),
            },
            sql: "-- returns: OrgRow\nselect name from orgs".to_string(),
            parameters: vec![],
            columns: vec![Column {
                name: "name".to_string(),
                field_name: "name".to_string(),
                column_type: ValueType::String,
                nullable: false,
            }],
        };

        let result = render_module(vec![&query_1, &query_2]);

        assert!(matches!(
            result,
            Err(Error::SharedRowTypeMismatch { row_type }) if row_type == "OrgRow"
        ));
    }
}
